// SEPTA stop ID -> position in the simple west-to-east list (same rule as app.js getStopIndexFromId).
const SHORT_BY_ID = {};
for (const stop of G_LINE_STOPS_FULL) SHORT_BY_ID[stop.stopId] = stop.shortName;
const INDEX_BY_SHORT = {};
G_LINE_STOPS_SIMPLE.forEach((stop, i) => { if (!(stop.shortName in INDEX_BY_SHORT)) INDEX_BY_SHORT[stop.shortName] = i; });

export function stopIndexFromId(stopId) {
    const short = SHORT_BY_ID[String(stopId)];
    if (short === undefined) return -1;
    const idx = INDEX_BY_SHORT[short];
    return idx === undefined ? -1 : idx;
}

// A readable name for a position, preferring the "Girard Av & ..." style entry.
export function stopDisplayName(index) {
    const simple = G_LINE_STOPS_SIMPLE[index];
    if (!simple) return '';
    const matches = G_LINE_STOPS_FULL.filter(s => s.shortName === simple.shortName);
    const preferred = matches.find(s => /Girard/.test(s.name)) || matches[0];
    return preferred ? preferred.name : simple.name;
}
